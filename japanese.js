// Japanese date labels keep the weekday visually separate from the day of month.
function japaneseDate(date){
 const day=new Intl.DateTimeFormat('ja',{timeZone:'Europe/Rome',year:'numeric',month:'long',day:'numeric'}).format(date);
 const weekday=new Intl.DateTimeFormat('ja',{timeZone:'Europe/Rome',weekday:'long'}).format(date);
 return day+'（'+weekday+'）';
}
